// String - ტექსტური მონაცემი
let name = "rati";
let city = "rustavi";

// Number - რიცხვითი მონაცემი
let age = 16;
let price = 25.5;

// Boolean - ლოგიკური მონაცემი (true ან false)
let isStudent = true;
let isAdult = false;

// Undefined - ცვლადი, რომელსაც მნიშვნელობა არ აქვს მინიჭებული
let x;
let y;

// Null - განზრახ მინიჭებული ცარიელი მნიშვნელობა
let car = null;
let phone = null;

// Object - ობიექტი, რომელიც ინახავს მონაცემებს
let person = { name: "Nika", age: 17 };
let book = { title: "JavaScript", pages: 200 };

// Array - მასივი, რომელიც რამდენიმე მნიშვნელობას ინახავს
let fruits = ["Apple", "Banana", "Orange"];
let numbers = [10, 20, 30];